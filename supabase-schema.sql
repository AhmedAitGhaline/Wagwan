insert into public.customers(full_name,phone,city,orders_count,total_spent,status,updated_at)
select trim(o.first_name||' '||o.last_name), trim(o.phone), (array_agg(o.city order by o.created_at desc))[1], count(*)::integer, coalesce(sum(o.total),0), case when count(*)>=3 then 'Actif' else 'Normal' end, now()
from public.orders o
group by trim(o.phone), trim(o.first_name||' '||o.last_name)
on conflict(phone) do update set
  full_name=excluded.full_name, city=excluded.city, orders_count=excluded.orders_count, total_spent=excluded.total_spent, status=excluded.status, updated_at=now();

-- Keep the dedicated customer table in sync when a COD order is created.
create or replace function public.upsert_customer_from_order()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.customers(full_name,phone,city,orders_count,total_spent,status,updated_at)
  values(trim(new.first_name||' '||new.last_name),trim(new.phone),trim(new.city),1,new.total,'Normal',now())
  on conflict(phone) do update set
    full_name=excluded.full_name,
    city=excluded.city,
    orders_count=public.customers.orders_count+1,
    total_spent=public.customers.total_spent+excluded.total,
    status=case when public.customers.orders_count+1>=3 then 'Actif' else 'Normal' end,
    updated_at=now();
  return new;
end;
$$;
drop trigger if exists trg_upsert_customer_from_order on public.orders;
create trigger trg_upsert_customer_from_order after insert on public.orders for each row execute function public.upsert_customer_from_order();

