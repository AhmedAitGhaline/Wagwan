create or replace function public.create_cod_order(
  p_first_name text,
  p_last_name text,
  p_phone text,
  p_address text,
  p_city text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  p public.products%rowtype;
  o public.orders%rowtype;
  requested_size text;
  requested_qty integer;
  current_stock integer;
  sub numeric(12,2) := 0;
  ship numeric(12,2) := 0;
begin
  if length(trim(p_first_name)) not between 1 and 80 or length(trim(p_last_name)) not between 1 and 80 then raise exception 'Invalid name'; end if;
  if length(trim(p_address)) not between 1 and 300 or length(trim(p_city)) not between 1 and 100 then raise exception 'Invalid address or city'; end if;
  if trim(p_phone) !~ '^(\+212|0)[67][0-9]{8}$' then raise exception 'Invalid Moroccan phone number'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items)=0 or jsonb_array_length(p_items)>30 then raise exception 'Invalid cart'; end if;

  for item in select * from jsonb_array_elements(p_items) loop
    select * into p from public.products where id=(item->>'product_id')::uuid and is_active=true for update;
    if not found then raise exception 'Product not available'; end if;
    requested_size := upper(item->>'size'); requested_qty := (item->>'quantity')::integer;
    if requested_size not in ('S','M','L','XL') or requested_qty < 1 or requested_qty > 50 then raise exception 'Invalid item'; end if;
    current_stock := case requested_size when 'S' then p.stock_s when 'M' then p.stock_m when 'L' then p.stock_l else p.stock_xl end;
    if current_stock < requested_qty then raise exception 'Out of stock: % size %', p.name, requested_size; end if;
    sub := sub + (p.price * requested_qty);
  end loop;

  insert into public.orders(first_name,last_name,phone,address,city,status,payment_method,subtotal,shipping,total)
  values(trim(p_first_name),trim(p_last_name),trim(p_phone),trim(p_address),trim(p_city),'pending','COD',sub,ship,sub+ship)
  returning * into o;

  for item in select * from jsonb_array_elements(p_items) loop
    select * into p from public.products where id=(item->>'product_id')::uuid for update;
    requested_size := upper(item->>'size'); requested_qty := (item->>'quantity')::integer;
    insert into public.order_items(order_id,product_id,product_name,product_image_url,size,quantity,unit_price,line_total)
    values(o.id,p.id,p.name,p.main_image_url,requested_size,requested_qty,p.price,p.price*requested_qty);
    case requested_size
      when 'S' then update public.products set stock_s=stock_s-requested_qty,updated_at=now() where id=p.id;
      when 'M' then update public.products set stock_m=stock_m-requested_qty,updated_at=now() where id=p.id;
      when 'L' then update public.products set stock_l=stock_l-requested_qty,updated_at=now() where id=p.id;
      when 'XL' then update public.products set stock_xl=stock_xl-requested_qty,updated_at=now() where id=p.id;
    end case;
  end loop;
  return jsonb_build_object('id',o.id,'order_number',o.order_number,'total',o.total);
end;
$$;
